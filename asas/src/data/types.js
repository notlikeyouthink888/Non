export const TYPE_BY_ID = Object.fromEntries(REPORT_TYPES.map((t) => [t.id, t]));

export function getType(id) {
  return TYPE_BY_ID[id] || TYPE_BY_ID.theory;
}

/** أقسام النوع الخاصة بمادة معيّنة (بعض الأقسام لا تظهر إلا في مواد بعينها). */
export function sectionsOf(type, cat) {
  const t = typeof type === 'string' ? getType(type) : type;
  return t.sections.filter((s) => !s.only || (cat && s.only.includes(cat)));
}

